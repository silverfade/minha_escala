const assert = require('node:assert/strict');
const { calculate } = require('../src/schedule.js');
const run = config => calculate({ anchor: '2026-10-08', rest: 1, work: 6, until: '2026-11', ...config });
const result = run();
assert.deepEqual(result.blocks.slice(0, 4), [['2026-10-08'], ['2026-10-15', '2026-10-16'], ['2026-10-23'], ['2026-10-30', '2026-10-31']]);
assert.deepEqual(result.blocks[4], ['2026-11-07']);
assert.deepEqual(run({ rest: 2 }).blocks[1], ['2026-10-16']);
assert.deepEqual(run({ anchor: '2028-02-22', until: '2028-03' }).blocks[1], ['2028-02-29', '2028-03-01']);
assert.deepEqual(run({ anchor: '2026-12-25', until: '2027-01' }).blocks[1], ['2027-01-01', '2027-01-02']);
assert.equal(run({ anchor: '2026-10-31', rest: 2, until: '2026-10' }).days.length, 1);
assert.throws(() => run({ until: '2026-09' }));
assert.throws(() => run({ work: 0 }));
assert.throws(() => run({ anchor: '2026-02-30' }));
assert.deepEqual(run({ mode: 'fixed', rest: 2 }).blocks.slice(0, 4), [['2026-10-08', '2026-10-09'], ['2026-10-16', '2026-10-17'], ['2026-10-24', '2026-10-25'], ['2026-11-01', '2026-11-02']]);
assert.deepEqual(run({ mode: 'fixed', rest: 1 }).blocks.slice(0, 3), [['2026-10-08'], ['2026-10-15'], ['2026-10-22']]);
assert.deepEqual(run({ mode: 'fixed', work: 5, rest: 2 }).blocks[1], ['2026-10-15', '2026-10-16']);
assert.deepEqual(run({ mode: 'fixed', work: 4, rest: 2 }).blocks[1], ['2026-10-14', '2026-10-15']);
assert.deepEqual(run({ mode: 'fixed', work: 3, rest: 3 }).blocks[1], ['2026-10-14', '2026-10-15', '2026-10-16']);
assert.throws(() => run({ rest: 3 }));
assert.throws(() => run({ mode: 'unknown' }));
console.log('16 verificações passaram: modelos fixos, personalizado, alternância e continuidade entre meses e anos.');
